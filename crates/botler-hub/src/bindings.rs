//! TypeScript bindings for the web app, generated from the Rust types with ts-rs.
//!
//! [`generate`] writes one `.ts` file per type, `routes.ts` (the typed route table from
//! [`crate::wire`]) and `index.ts`. The output is committed in `frontend/src/generated/`; the
//! `typescript_bindings_are_current` test fails when it is stale, and regenerates it with
//! `BOTLER_UPDATE_BINDINGS=1 cargo test -p botler --test bindings`.

use std::any::TypeId;
use std::collections::{BTreeMap, HashSet};
use std::path::{Path, PathBuf};

use ts_rs::{Config, TS, TypeVisitor};

use crate::wire::{TypeSink, route_table, route_types};

#[derive(Debug, thiserror::Error)]
pub enum BindingsError {
    #[error("exporting TypeScript: {0}")]
    Export(#[from] ts_rs::ExportError),
    #[error("io: {0}")]
    Io(#[from] std::io::Error),
}

const HEADER: &str = "// Generated by botler (crates/botler-hub/src/bindings.rs). Do not edit.\n\n";

/// Exports every type it is given (with its dependencies) and remembers the names a
/// `routes.ts` import needs.
struct Exporter<'a> {
    cfg: &'a Config,
    /// TypeScript name → path relative to the output directory.
    names: BTreeMap<String, PathBuf>,
    /// Types already handled (some, like JSON values, refer to themselves).
    seen: HashSet<TypeId>,
    error: Option<ts_rs::ExportError>,
}

impl Exporter<'_> {
    fn export<T: TS + 'static + ?Sized>(&mut self) {
        if self.error.is_some() || !self.seen.insert(TypeId::of::<T>()) {
            return;
        }
        match T::output_path() {
            Some(path) => {
                self.names.insert(T::ident(self.cfg), path);
                if let Err(e) = T::export_all(self.cfg) {
                    self.error = Some(e);
                }
            }
            // `Vec<T>`, `Option<T>`, ...: export what they contain.
            None => {
                T::visit_dependencies(self);
                T::visit_generics(self);
            }
        }
    }
}

impl TypeVisitor for Exporter<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        self.export::<T>();
    }
}

impl TypeSink for Exporter<'_> {
    fn add<T: TS + 'static + ?Sized>(&mut self) {
        self.export::<T>();
    }
}

fn import_path(rel: &Path) -> String {
    let s = rel.to_string_lossy().replace('\\', "/");
    format!("./{}", s.strip_suffix(".ts").unwrap_or(&s))
}

/// Path parameters (`{name}`) of a route path.
fn params(path: &str) -> Vec<&str> {
    path.split('/').filter_map(|seg| seg.strip_prefix('{')?.strip_suffix('}')).collect()
}

fn routes_ts(cfg: &Config, names: &BTreeMap<String, PathBuf>) -> String {
    let table = route_table(cfg);
    // Import only the names the table mentions (unused imports fail the frontend's type check).
    let used = |name: &str| {
        table
            .iter()
            .flat_map(|r| [r.query.as_deref(), r.body.as_deref(), Some(r.response.as_str())])
            .flatten()
            .any(|ty| ty.split(|c: char| !(c.is_alphanumeric() || c == '_')).any(|word| word == name))
    };
    let mut s = String::from(HEADER);
    for (name, path) in names.iter().filter(|(n, _)| used(n)) {
        s.push_str(&format!("import type {{ {name} }} from \"{}\";\n", import_path(path)));
    }
    s.push_str("\n/** Every HTTP route: method, path, parameters, query, body and response types. */\n");
    s.push_str("export interface Routes {\n");
    for r in &table {
        let ps = params(r.path);
        let params_ty = if ps.is_empty() {
            "Record<string, never>".to_string()
        } else {
            format!("{{ {} }}", ps.iter().map(|p| format!("{p}: string")).collect::<Vec<_>>().join("; "))
        };
        s.push_str(&format!(
            "  {}: {{ method: \"{}\"; path: \"{}\"; params: {}; query: {}; body: {}; response: {} }};\n",
            r.name,
            r.method,
            r.path,
            params_ty,
            r.query.as_deref().unwrap_or("never"),
            r.body.as_deref().unwrap_or("never"),
            r.response,
        ));
    }
    s.push_str("}\n\nexport const ROUTES: { [K in keyof Routes]: { method: Routes[K][\"method\"]; path: Routes[K][\"path\"] } } = {\n");
    for r in &table {
        s.push_str(&format!("  {}: {{ method: \"{}\", path: \"{}\" }},\n", r.name, r.method, r.path));
    }
    s.push_str("};\n");
    s
}

fn ts_files(dir: &Path, root: &Path, out: &mut Vec<PathBuf>) -> std::io::Result<()> {
    for e in std::fs::read_dir(dir)? {
        let p = e?.path();
        if p.is_dir() {
            ts_files(&p, root, out)?;
        } else if p.extension().is_some_and(|x| x == "ts") {
            out.push(p.strip_prefix(root).map_err(std::io::Error::other)?.to_path_buf());
        }
    }
    Ok(())
}

/// Write all bindings into `dir` (which should be empty).
pub fn generate(dir: &Path) -> Result<(), BindingsError> {
    // i64/u64 values (counts, tokens, exit codes) stay far below 2^53.
    let cfg = Config::new().with_out_dir(dir).with_large_int("number");
    let mut ex = Exporter { cfg: &cfg, names: BTreeMap::new(), seen: HashSet::new(), error: None };
    route_types(&mut ex);
    let route_names = ex.names.clone();
    ex.add::<crate::live::ClientMessage>();
    ex.add::<crate::live::ServerMessage>();
    ex.add::<botler_core::payloads::BuiltinPayload>();
    if let Some(e) = ex.error {
        return Err(e.into());
    }
    std::fs::write(dir.join("routes.ts"), routes_ts(&cfg, &route_names))?;

    let mut files = Vec::new();
    ts_files(dir, dir, &mut files)?;
    files.sort();
    let mut index = String::from(HEADER);
    for f in files.iter().filter(|f| f.as_path() != Path::new("index.ts")) {
        index.push_str(&format!("export type * from \"{}\";\n", import_path(f)));
    }
    index.push_str("export { ROUTES } from \"./routes\";\n");
    std::fs::write(dir.join("index.ts"), index)?;
    Ok(())
}

